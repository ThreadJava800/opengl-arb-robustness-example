/*
 * robust_triangle_wl.c
 *
 * A minimal OpenGL program with NO GLFW. It uses:
 *   - libwayland-client + xdg-shell  : native Wayland windowing (KDE KWin target)
 *   - libwayland-egl + EGL           : GL context/surface on the Wayland surface
 *   - GL_ARB_robustness              : GPU-reset detection + recovery
 *
 * It draws a spinning RGB triangle, logs every rendered frame, and when the GPU
 * resets the context (LOSE_CONTEXT_ON_RESET) it rebuilds the EGL context and
 * resumes rendering.
 *
 * Keys:  ESC = quit,  R = simulate the recovery path (no real GPU hang needed).
 *        You can also just close the window.
 *
 * Build:  make            (runs wayland-scanner, then compiles)
 * Run:    ./robust_triangle_wl    (from a Wayland/KWin session)
 */

#define _POSIX_C_SOURCE 199309L

#include <wayland-client.h>
#include <wayland-egl.h>
#include <EGL/egl.h>
#include <GL/gl.h>
#include "xdg-shell-client-protocol.h"   /* generated by wayland-scanner */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <time.h>
#include <stdint.h>
#include <unistd.h>
#include <poll.h>
#include <errno.h>

/* --- GL_ARB_robustness enums (defined locally; no glext.h dependency) --- */
#ifndef GL_GUILTY_CONTEXT_RESET_ARB
#define GL_GUILTY_CONTEXT_RESET_ARB    0x8253
#define GL_INNOCENT_CONTEXT_RESET_ARB  0x8254
#define GL_UNKNOWN_CONTEXT_RESET_ARB   0x8255
#endif

/* --- EGL robustness attribs (EGL 1.5 / EGL_EXT_create_context_robustness).
 *     The EXT and core tokens share the same numeric values, so these work
 *     against either, and we fall back to a plain context if unsupported. --- */
#ifndef EGL_CONTEXT_OPENGL_ROBUST_ACCESS
#define EGL_CONTEXT_OPENGL_ROBUST_ACCESS 0x30BF
#endif
#ifndef EGL_CONTEXT_OPENGL_RESET_NOTIFICATION_STRATEGY
#define EGL_CONTEXT_OPENGL_RESET_NOTIFICATION_STRATEGY 0x3138
#endif
#ifndef EGL_LOSE_CONTEXT_ON_RESET
#define EGL_LOSE_CONTEXT_ON_RESET 0x31BF
#endif

typedef GLenum (*PFN_glGetGraphicsResetStatus)(void);

typedef struct {
    struct wl_display    *display;
    struct wl_registry   *registry;
    struct wl_compositor *compositor;
    struct xdg_wm_base   *wm_base;
    struct wl_seat       *seat;
    struct wl_keyboard   *keyboard;
    struct wl_surface    *surface;
    struct xdg_surface   *xsurface;
    struct xdg_toplevel  *toplevel;
    struct wl_egl_window *egl_window;

    EGLDisplay egl_dpy;
    EGLConfig  egl_cfg;
    EGLSurface egl_surf;
    EGLContext context;

    PFN_glGetGraphicsResetStatus getResetStatus; /* NULL if unavailable */

    int width, height;
    int pending_w, pending_h;
    int running;
    int force_reset;   /* set by R key */
    int robust;        /* did we actually get a robust context? */
} App;

static double now_seconds(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec * 1e-9;
}

static const char *reset_status_name(GLenum s)
{
    switch (s) {
        case GL_NO_ERROR:                    return "GL_NO_ERROR";
        case GL_GUILTY_CONTEXT_RESET_ARB:    return "GL_GUILTY_CONTEXT_RESET_ARB";
        case GL_INNOCENT_CONTEXT_RESET_ARB:  return "GL_INNOCENT_CONTEXT_RESET_ARB";
        case GL_UNKNOWN_CONTEXT_RESET_ARB:   return "GL_UNKNOWN_CONTEXT_RESET_ARB";
        default:                             return "unexpected status";
    }
}

/* ------------------------------ Wayland glue ------------------------------ */

static void kb_keymap(void *d, struct wl_keyboard *k, uint32_t fmt, int32_t fd, uint32_t sz)
{ (void)d;(void)k;(void)fmt;(void)sz; if (fd >= 0) close(fd); }   /* ignore keymap */
static void kb_enter(void *d, struct wl_keyboard *k, uint32_t s, struct wl_surface *su, struct wl_array *ks)
{ (void)d;(void)k;(void)s;(void)su;(void)ks; }
static void kb_leave(void *d, struct wl_keyboard *k, uint32_t s, struct wl_surface *su)
{ (void)d;(void)k;(void)s;(void)su; }
static void kb_mods(void *d, struct wl_keyboard *k, uint32_t s, uint32_t md, uint32_t ml, uint32_t lk, uint32_t grp)
{ (void)d;(void)k;(void)s;(void)md;(void)ml;(void)lk;(void)grp; }
static void kb_repeat(void *d, struct wl_keyboard *k, int32_t r, int32_t delay)
{ (void)d;(void)k;(void)r;(void)delay; }

static void kb_key(void *data, struct wl_keyboard *k, uint32_t serial,
                   uint32_t time, uint32_t key, uint32_t state)
{
    (void)k; (void)serial; (void)time;
    if (state != WL_KEYBOARD_KEY_STATE_PRESSED) return;
    App *a = (App *)data;
    /* evdev keycodes: ESC = 1, R = 19 (physical-key based, layout-independent) */
    if (key == 1) {
        a->running = 0;
    } else if (key == 19) {
        a->force_reset = 1;
        printf("[input] simulated reset requested (R)\n");
    }
}

static const struct wl_keyboard_listener kb_listener = {
    .keymap = kb_keymap, .enter = kb_enter, .leave = kb_leave,
    .key = kb_key, .modifiers = kb_mods, .repeat_info = kb_repeat,
};

static void seat_caps(void *data, struct wl_seat *seat, uint32_t caps)
{
    App *a = (App *)data;
    if ((caps & WL_SEAT_CAPABILITY_KEYBOARD) && !a->keyboard) {
        a->keyboard = wl_seat_get_keyboard(seat);
        wl_keyboard_add_listener(a->keyboard, &kb_listener, a);
    }
}
static void seat_name(void *d, struct wl_seat *s, const char *n){ (void)d;(void)s;(void)n; }
static const struct wl_seat_listener seat_listener = { .capabilities = seat_caps, .name = seat_name };

static void wm_ping(void *d, struct xdg_wm_base *b, uint32_t serial)
{ (void)d; xdg_wm_base_pong(b, serial); }
static const struct xdg_wm_base_listener wm_listener = { .ping = wm_ping };

static void xsurf_configure(void *data, struct xdg_surface *xs, uint32_t serial)
{
    App *a = (App *)data;
    xdg_surface_ack_configure(xs, serial);
    if (a->egl_window && a->pending_w > 0 && a->pending_h > 0 &&
        (a->pending_w != a->width || a->pending_h != a->height)) {
        a->width  = a->pending_w;
        a->height = a->pending_h;
        wl_egl_window_resize(a->egl_window, a->width, a->height, 0, 0);
    }
}
static const struct xdg_surface_listener xsurf_listener = { .configure = xsurf_configure };

static void xtop_configure(void *data, struct xdg_toplevel *t,
                           int32_t w, int32_t h, struct wl_array *states)
{
    (void)t; (void)states;
    App *a = (App *)data;
    if (w > 0 && h > 0) { a->pending_w = w; a->pending_h = h; }
}
static void xtop_close(void *data, struct xdg_toplevel *t)
{ (void)t; ((App *)data)->running = 0; }
static const struct xdg_toplevel_listener xtop_listener = {
    .configure = xtop_configure, .close = xtop_close,
};

static void reg_global(void *data, struct wl_registry *reg, uint32_t name,
                       const char *iface, uint32_t ver)
{
    App *a = (App *)data;
    if (!strcmp(iface, wl_compositor_interface.name))
        a->compositor = wl_registry_bind(reg, name, &wl_compositor_interface, ver < 4 ? ver : 4);
    else if (!strcmp(iface, xdg_wm_base_interface.name))
        a->wm_base = wl_registry_bind(reg, name, &xdg_wm_base_interface, 1);
    else if (!strcmp(iface, wl_seat_interface.name))
        a->seat = wl_registry_bind(reg, name, &wl_seat_interface, 1);
}
static void reg_remove(void *d, struct wl_registry *r, uint32_t name){ (void)d;(void)r;(void)name; }
static const struct wl_registry_listener reg_listener = { .global = reg_global, .global_remove = reg_remove };

/* Non-blocking Wayland event pump (so animation keeps running). */
static int pump_wayland(struct wl_display *display)
{
    while (wl_display_prepare_read(display) != 0) {
        if (wl_display_dispatch_pending(display) == -1) return -1;
    }
    if (wl_display_flush(display) == -1 && errno != EAGAIN) {
        wl_display_cancel_read(display);
        return -1;
    }
    struct pollfd pfd = { .fd = wl_display_get_fd(display), .events = POLLIN };
    if (poll(&pfd, 1, 0) > 0 && (pfd.revents & POLLIN))
        wl_display_read_events(display);
    else
        wl_display_cancel_read(display);
    return wl_display_dispatch_pending(display);
}

/* ------------------------------ EGL / GL ---------------------------------- */

static int egl_create_context(App *a)
{
    EGLint robust_attribs[] = {
        EGL_CONTEXT_OPENGL_ROBUST_ACCESS,                   EGL_TRUE,
        EGL_CONTEXT_OPENGL_RESET_NOTIFICATION_STRATEGY,     EGL_LOSE_CONTEXT_ON_RESET,
        EGL_NONE
    };

    a->context = eglCreateContext(a->egl_dpy, a->egl_cfg, EGL_NO_CONTEXT, robust_attribs);
    if (a->context == EGL_NO_CONTEXT) {
        fprintf(stderr, "[egl] robust context unavailable (0x%x), using plain context\n",
                eglGetError());
        EGLint plain[] = { EGL_NONE };
        a->context = eglCreateContext(a->egl_dpy, a->egl_cfg, EGL_NO_CONTEXT, plain);
        if (a->context == EGL_NO_CONTEXT) {
            fprintf(stderr, "[egl] eglCreateContext failed: 0x%x\n", eglGetError());
            return 0;
        }
        a->robust = 0;
    } else {
        a->robust = 1;
    }

    if (!eglMakeCurrent(a->egl_dpy, a->egl_surf, a->egl_surf, a->context)) {
        fprintf(stderr, "[egl] eglMakeCurrent failed: 0x%x\n", eglGetError());
        return 0;
    }
    eglSwapInterval(a->egl_dpy, 1);

    /* Load reset-status entry point: ARB first, then core/KHR fallbacks. */
    a->getResetStatus =
        (PFN_glGetGraphicsResetStatus)eglGetProcAddress("glGetGraphicsResetStatusARB");
    if (!a->getResetStatus)
        a->getResetStatus =
            (PFN_glGetGraphicsResetStatus)eglGetProcAddress("glGetGraphicsResetStatus");
    if (!a->getResetStatus)
        a->getResetStatus =
            (PFN_glGetGraphicsResetStatus)eglGetProcAddress("glGetGraphicsResetStatusKHR");

    const char *vendor   = (const char *)glGetString(GL_VENDOR);
    const char *renderer = (const char *)glGetString(GL_RENDERER);
    const char *version  = (const char *)glGetString(GL_VERSION);
    const char *exts     = (const char *)glGetString(GL_EXTENSIONS);
    int have_arb = (exts && strstr(exts, "GL_ARB_robustness")) ? 1 : 0;

    printf("[gl] vendor=%s | renderer=%s | version=%s\n",
           vendor ? vendor : "?", renderer ? renderer : "?", version ? version : "?");
    printf("[gl] robust context obtained       : %s\n", a->robust ? "yes" : "NO");
    printf("[gl] GL_ARB_robustness advertised   : %s\n", have_arb ? "yes" : "no");
    printf("[gl] reset-status query loaded      : %s\n",
           a->getResetStatus ? "yes" : "no (resets won't be detectable)");

    /* Re-create any persistent GL objects (textures, VBOs, shaders) here after
     * a reset. This demo uses immediate mode, so there's nothing to rebuild. */

    a->force_reset = 0;
    return 1;
}

static void egl_destroy_context(App *a)
{
    if (a->egl_dpy != EGL_NO_DISPLAY) {
        eglMakeCurrent(a->egl_dpy, EGL_NO_SURFACE, EGL_NO_SURFACE, EGL_NO_CONTEXT);
        if (a->context != EGL_NO_CONTEXT) {
            eglDestroyContext(a->egl_dpy, a->context);
            a->context = EGL_NO_CONTEXT;
        }
    }
    a->getResetStatus = NULL;
}

static void render(App *a, double t)
{
    if (a->width <= 0 || a->height <= 0) return;
    glViewport(0, 0, a->width, a->height);

    glClearColor(0.08f, 0.09f, 0.12f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT);

    float aspect = (float)a->height / (float)a->width;
    float r = 0.6f;
    float colors[3][3] = { {1,0,0}, {0,1,0}, {0,0,1} };

    glBegin(GL_TRIANGLES);
    for (int i = 0; i < 3; i++) {
        float ang = (float)t + (float)i * (2.0f * 3.14159265f / 3.0f);
        glColor3f(colors[i][0], colors[i][1], colors[i][2]);
        glVertex2f(r * cosf(ang) * aspect, r * sinf(ang));
    }
    glEnd();
}

/* --------------------------------- main ----------------------------------- */

int main(void)
{
    App a;
    memset(&a, 0, sizeof a);
    a.width = 640; a.height = 480;
    a.running = 1;

    /* 1. Connect + fetch globals. */
    a.display = wl_display_connect(NULL);
    if (!a.display) { fprintf(stderr, "cannot connect to a Wayland display (is WAYLAND_DISPLAY set?)\n"); return 1; }
    a.registry = wl_display_get_registry(a.display);
    wl_registry_add_listener(a.registry, &reg_listener, &a);
    wl_display_roundtrip(a.display);

    if (!a.compositor || !a.wm_base) {
        fprintf(stderr, "compositor is missing wl_compositor or xdg_wm_base\n");
        return 1;
    }
    xdg_wm_base_add_listener(a.wm_base, &wm_listener, &a);
    if (a.seat) wl_seat_add_listener(a.seat, &seat_listener, &a);

    /* 2. Build the xdg-shell toplevel. */
    a.surface  = wl_compositor_create_surface(a.compositor);
    a.xsurface = xdg_wm_base_get_xdg_surface(a.wm_base, a.surface);
    xdg_surface_add_listener(a.xsurface, &xsurf_listener, &a);
    a.toplevel = xdg_surface_get_toplevel(a.xsurface);
    xdg_toplevel_add_listener(a.toplevel, &xtop_listener, &a);
    xdg_toplevel_set_title(a.toplevel, "ARB_robustness demo (Wayland/KWin, no GLFW)");
    xdg_toplevel_set_app_id(a.toplevel, "robust_triangle_wl");
    wl_surface_commit(a.surface);          /* triggers the first configure */
    wl_display_roundtrip(a.display);       /* ack happens in xsurf_configure */

    /* 3. Bring up EGL. */
    a.egl_dpy = eglGetDisplay((EGLNativeDisplayType)a.display);
    if (a.egl_dpy == EGL_NO_DISPLAY || !eglInitialize(a.egl_dpy, NULL, NULL)) {
        fprintf(stderr, "[egl] eglInitialize failed\n"); return 1;
    }
    if (!eglBindAPI(EGL_OPENGL_API)) {
        fprintf(stderr, "[egl] eglBindAPI(EGL_OPENGL_API) failed: 0x%x\n", eglGetError()); return 1;
    }
    EGLint cfg_attribs[] = {
        EGL_SURFACE_TYPE,    EGL_WINDOW_BIT,
        EGL_RENDERABLE_TYPE, EGL_OPENGL_BIT,
        EGL_RED_SIZE, 8, EGL_GREEN_SIZE, 8, EGL_BLUE_SIZE, 8, EGL_ALPHA_SIZE, 8,
        EGL_NONE
    };
    EGLint n = 0;
    if (!eglChooseConfig(a.egl_dpy, cfg_attribs, &a.egl_cfg, 1, &n) || n == 0) {
        fprintf(stderr, "[egl] no matching EGLConfig\n"); return 1;
    }
    printf("[egl] EGL_VERSION=%s\n", eglQueryString(a.egl_dpy, EGL_VERSION));

    /* 4. Wayland-backed EGL surface. */
    a.egl_window = wl_egl_window_create(a.surface, a.width, a.height);
    if (!a.egl_window) { fprintf(stderr, "[egl] wl_egl_window_create failed\n"); return 1; }
    a.egl_surf = eglCreateWindowSurface(a.egl_dpy, a.egl_cfg,
                                        (EGLNativeWindowType)a.egl_window, NULL);
    if (a.egl_surf == EGL_NO_SURFACE) {
        fprintf(stderr, "[egl] eglCreateWindowSurface failed: 0x%x\n", eglGetError()); return 1;
    }

    /* 5. Robust context. */
    if (!egl_create_context(&a)) return 1;

    /* 6. Main loop. */
    uint64_t frame = 0;
    double t0 = now_seconds();

    while (a.running) {
        if (pump_wayland(a.display) == -1) { fprintf(stderr, "[wl] display error\n"); break; }
        double t = now_seconds() - t0;

        /* Detect a GPU-initiated reset before using the context. */
        GLenum status = GL_NO_ERROR;
        if (a.getResetStatus) status = a.getResetStatus();

        if (status != GL_NO_ERROR || a.force_reset) {
            if (a.force_reset)
                printf("[reset] simulated reset -> rebuilding context\n");
            else
                printf("[reset] GPU reset detected: %s -> rebuilding context\n",
                       reset_status_name(status));

            egl_destroy_context(&a);

            int ok = 0;
            for (int attempt = 1; attempt <= 10 && !ok; attempt++) {
                struct timespec backoff = { 0, 200L * 1000L * 1000L }; /* 200 ms */
                nanosleep(&backoff, NULL);
                ok = egl_create_context(&a);
                if (!ok) fprintf(stderr, "[reset] rebuild attempt %d failed\n", attempt);
            }
            if (!ok) { fprintf(stderr, "[reset] could not recover, giving up\n"); break; }
            printf("[reset] recovery complete, resuming rendering\n");
            continue;
        }

        /* Render + log every frame. */
        printf("[frame] t=%.3f  rendering frame %llu\n", t, (unsigned long long)frame);
        fflush(stdout);
        render(&a, t);

        if (!eglSwapBuffers(a.egl_dpy, a.egl_surf)) {
            EGLint e = eglGetError();
            if (e == EGL_CONTEXT_LOST) {       /* EGL's own signal of a reset */
                printf("[egl] EGL_CONTEXT_LOST on swap -> will recover\n");
                a.force_reset = 1;
            } else {
                fprintf(stderr, "[egl] eglSwapBuffers error 0x%x\n", e);
            }
        }
        frame++;
    }

    /* Cleanup. */
    egl_destroy_context(&a);
    if (a.egl_surf)   eglDestroySurface(a.egl_dpy, a.egl_surf);
    if (a.egl_window) wl_egl_window_destroy(a.egl_window);
    if (a.egl_dpy)    eglTerminate(a.egl_dpy);
    if (a.toplevel)   xdg_toplevel_destroy(a.toplevel);
    if (a.xsurface)   xdg_surface_destroy(a.xsurface);
    if (a.surface)    wl_surface_destroy(a.surface);
    wl_display_disconnect(a.display);
    return 0;
}

